  await page.keyboard.press('Escape'); await expect(tip).not.toBeVisible(); await expect(button).toBeFocused();
  await page.keyboard.press('Enter'); await expect(tip).toBeVisible();
  await page.keyboard.press('Tab'); await expect(tip).not.toBeVisible();
  await button.click(); await expect(tip).toBeVisible();
  await shot(page, 'desktop-tooltip');
  await page.locator('#sky-full-star-map').click(); await expect(tip).not.toBeVisible();
  await page.locator('#sky-star-map-deep').click();
  assert.equal(await page.evaluate(() => window.skyApp.state.environment.darkSkyLimitingMagnitude), 10);
  await page.locator('#sky-observe-appearance').click();
  await expect(page.locator('#sky-observe-appearance')).toHaveAttribute('aria-pressed', 'true');
  report.checks.push('Tooltip hover, hover transfer, focus, Escape without focus loss, Enter, Tab and outside dismissal; display actions remain functional.');
  await page.locator('#sky-density').selectOption('reference'); await button.click();
  await expect(tip).toBeVisible(); await shot(page, 'reference-tooltip');
  assert.ok(await page.locator('.panel-scroll').evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.keyboard.press('Escape'); await page.locator('#sky-density').selectOption('teaching');

