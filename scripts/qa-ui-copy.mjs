  await remove.click(); await shot(page, 'scene-delete-confirmation'); await confirm.click();
  assert.equal(await saved.inputValue(), ''); await expect(saved).toBeFocused();
  assert.equal(await saved.locator(`option[value="${id}"]`).count(), 0);
  report.checks.push('Scene update/delete require visible consequences and explicit confirmation; cancel/Escape preserve record, safe focus and final deletion verified.');

  await openDetails(page, '.layer-section'); await openDetails(page, '#sky-refraction');
  await page.locator('#sky-pressure').fill('1300'); await page.locator('#sky-apply-refraction').click();
  await expect(page.locator('#sky-refraction-status')).toContainText('0至1200');
  assert.equal(await page.locator('#sky-pressure').inputValue(), '1300');
  await page.locator('#sky-pressure').fill('1010'); await page.locator('#sky-apply-refraction').click();
  await openDetails(page, '.course-equipment'); await openDetails(page, '.course-tools');
  await page.locator('.course-title').fill('核查课程');
  await expect(page.locator('.course-save-status')).toContainText('已保存在此设备', { timeout: 10000 });
  await shot(page, 'course');
  await page.locator('[data-ce="demo"]').click();
  await expect(page.locator('.course-replace-message')).toBeVisible(); await page.locator('[data-ce="course-replace-cancel"]').click();
  await openDetails(page, '.landscape-tools');
  await page.getByRole('button', { name: '全景地景格式说明', exact: true }).click();
  await expect(page.locator('#sky-landscape-format-help')).toBeVisible(); await shot(page, 'landscape-tooltip');
  await expect(page.locator('#sky-landscape-format-help')).toBeVisible();
  await page.keyboard.press('Escape');
  await openDetails(page, '.offline-section'); await expect(page.locator('#sky-check-update')).toBeVisible();
  await expect(page.locator('#sky-app-version')).toContainText('v0.3.0');
  report.checks.push('Input failure retains draft and correction; course autosave and replacement warning; landscape format help and offline/version entry remain available.');

  const missingDescriptions = await page.locator('[aria-describedby]').evaluateAll(nodes => nodes.flatMap(node => node.getAttribute('aria-describedby').split(/\s+/).filter(id => !document.getElementById(id))));
  assert.deepEqual(missingDescriptions, []);
  for (const node of await page.locator('.info-tip-trigger').all()) assert.ok(await node.getAttribute('aria-label'));
  report.checks.push('All info triggers have accessible names; every aria-describedby points to an existing element.');

  const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: 'reduce' });
  const mobile = await touch.newPage(); observe(mobile); await mobile.goto(url); await ready(mobile);
  await mobile.locator('[data-action="open-time"]').tap(); await openDetails(mobile, '.appearance-controls');
  const touchTip = mobile.getByRole('button', { name: '星图深度说明', exact: true });
  await touchTip.tap(); await expect(mobile.locator('#sky-star-map-depth-help')).toBeVisible();
  const rect = await mobile.locator('#sky-star-map-depth-help').boundingBox();
  assert.ok(rect.x >= 0 && rect.x + rect.width <= 390 && rect.y >= 0 && rect.y + rect.height <= 844);
  const target = await touchTip.boundingBox(); assert.ok(target.width >= 44 && target.height >= 44);
  await shot(mobile, 'mobile-tooltip'); await touchTip.tap(); await expect(mobile.locator('#sky-star-map-depth-help')).not.toBeVisible();
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
