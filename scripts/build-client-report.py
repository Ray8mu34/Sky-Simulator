def para(text, style='body'):
    # Link only explicit public URLs; project paths remain plain source locators.
    value = escape(text).replace('\n', '<br/>')
    value = re.sub(r'(https://[^\s<；。]+)', r'<link href="\1" color="#234C6E">\1</link>', value)
    return Paragraph(value, STYLES[style])

