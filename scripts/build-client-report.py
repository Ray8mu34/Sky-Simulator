        OUTPUT.parent.mkdir(exist_ok=True)
        QA.mkdir(parents=True, exist_ok=True)
        self.total = len(PAGES) + 1
        self.c = canvas.Canvas(str(OUTPUT), pagesize=A4, pageCompression=1)
        self.c.setTitle('三维全景夜空 项目功能说明与甲方审查报告')
