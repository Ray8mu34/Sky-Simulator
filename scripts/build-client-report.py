    def table(self, headers, rows, widths):
        widths = widths or [WIDTH/len(headers)]*len(headers)
        cells = [[para(v, 'headcell') for v in headers]]
        compact = len(rows) > 16
        cells += [[para(str(v), 'compactcell' if compact else 'cell') for v in row] for row in rows]
        t = Table(cells, colWidths=widths, hAlign='LEFT')
        t.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), LIGHT),
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('LEFTPADDING', (0,0), (-1,-1), 8), ('RIGHTPADDING', (0,0), (-1,-1), 8),
            ('TOPPADDING', (0,0), (-1,-1), 5 if compact else 7), ('BOTTOMPADDING', (0,0), (-1,-1), 5 if compact else 7),
            ('LINEBELOW', (0,0), (-1,0), 0.7, colors.HexColor('#B7C4CF')),
            ('LINEBELOW', (0,1), (-1,-1), 0.35, colors.HexColor('#D8DEE5')),
        ]))
        self.draw(t, 10)

    def diagram(self):
        c = self.c
        top = self.y
        rows = [('统一输入', '科学时间  观测地点  选中对象  图层与环境'),
                ('科学状态', '恒星与日月方向  月相  地平坐标  当地日事件'),
                ('联动展示', '地表  太空  天球  地平天球'),
                ('教学输出', '对象读数  教学场景  截图  JSON  分享链接')]
        height = 45
        for i,(label,text) in enumerate(rows):
            y = top-i*57-height
            c.setFillColor(LIGHT); c.roundRect(LEFT,y,WIDTH,height,4,fill=1,stroke=0)
            c.setFillColor(BLUE); c.setFont('HeadingCN',10.5); c.drawString(LEFT+12,y+17,label)
            c.setFillColor(INK); c.setFont('BodyCN',10); c.drawString(LEFT+93,y+17,text)
            if i<3:
                c.setStrokeColor(colors.HexColor('#839BAD'))
                c.line(W/2,y-2,W/2,y-10)
        self.y = top-4*57-2

    def toc(self):
        items = [(i+2,pg['title']) for i,pg in enumerate(PAGES) if pg['title']!='目录']
        for n,title in items:
            y = self.y
            self.c.setFont('BodyCN',10.3); self.c.setFillColor(INK)
            self.c.drawString(LEFT,y-12,title)
            self.c.setFillColor(MUTED)
            self.c.drawRightString(W-LEFT,y-12,str(n))
            self.c.linkRect('', f'page{n}', (LEFT,y-17,W-LEFT,y+2),relative=0,thickness=0)
            self.y -= 23
        self.y -= 9
        self.draw(para('阅读建议：第2至5页了解项目；第6至22页查看功能；第23至25页核对模型、验证和交付；第26至27页组织甲方试用审查。', 'small'))

    def run(self):
        self.cover()
        for i,pg in enumerate(PAGES,2):
            self.current = i
            self.y = H-114
            c = self.c
            c.bookmarkPage(f'page{i}')
            c.addOutlineEntry(pg['title'], f'page{i}',0)
            c.setFillColor(MUTED); c.setFont('BodyCN',8.5)
            c.drawString(LEFT,H-47,pg['section'])
            c.drawRightString(W-LEFT,H-47,'项目功能说明与甲方审查报告')
            c.setFillColor(INK); c.setFont('HeadingCN',19)
            c.drawString(LEFT,H-84,pg['title'])
            for block in pg['blocks']:
                if block[0]=='p': self.draw(para(block[1]),8)
                elif block[0]=='h': self.draw(para(block[1],'h2'),6)
                elif block[0]=='note':
                    self.draw(para(block[1],'small'),6)
                elif block[0]=='table': self.table(*block[1:])
                elif block[0]=='image':
                    ht = WIDTH*1080/1920
                    c.drawImage(str(ROOT/'media/screenshots'/block[1]), LEFT, self.y-ht,width=WIDTH,height=ht)
                    self.y -= ht+8
                    self.draw(para(block[2], 'caption'), 8)
                elif block[0]=='diagram': self.diagram()
                elif block[0]=='toc': self.toc()
            if self.y<BOTTOM:
                raise ValueError(f'Page {i}: footer overlap {self.y}')
            self.metrics.append({'page':i, 'title':pg['title'], 'content_bottom_pt':round(self.y,1)})
            self.footer(i, pg['section'], pg['refs'])
            c.showPage()
        c.save()
        (QA/'layout.json').write_text(json.dumps(self.metrics,ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps({'pdf':str(OUTPUT),'pages':self.total,'bytes':OUTPUT.stat().st_size},ensure_ascii=False))

